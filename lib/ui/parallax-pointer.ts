/**
 * lib/ui/parallax-pointer.ts — pointer parallax fields.
 * Containers marked .ui-parallax-field or [data-ui-parallax] publish
 * --pointer-x/--pointer-y (-1..1); children use their own --factor.
 */
import { IS_BROWSER, clamp, isFinePointer, prefersReducedMotion, qa, rafThrottle, setVar } from './dom'

export function mountParallaxPointer(): () => void {
  if (!IS_BROWSER || prefersReducedMotion() || !isFinePointer()) return () => {}

  const wired = new WeakSet<HTMLElement>()

  const wire = (el: HTMLElement) => {
    if (wired.has(el)) return
    wired.add(el)
    const move = rafThrottle((cx: number, cy: number) => {
      const r = el.getBoundingClientRect()
      setVar(el, '--pointer-x', clamp(((cx - r.left) / r.width - 0.5) * 2, -1, 1).toFixed(3))
      setVar(el, '--pointer-y', clamp(((cy - r.top) / r.height - 0.5) * 2, -1, 1).toFixed(3))
    })
    el.addEventListener('pointermove', (e) => move(e.clientX, e.clientY), { passive: true })
    el.addEventListener('pointerleave', () => {
      setVar(el, '--pointer-x', '0')
      setVar(el, '--pointer-y', '0')
    })
  }

  const scan = () => qa('.ui-parallax-field, [data-ui-parallax]').forEach(wire)
  scan()
  const observer = new MutationObserver(scan)
  observer.observe(document.body, { childList: true, subtree: true })
  return () => observer.disconnect()
}

/* ------------------------------------------------------------------
   Imperative surface · parallax-pointer
   ------------------------------------------------------------------
   Uniform window-level contract so app code (route transitions,
   analytics beacons, QA harnesses) can drive this effect without
   holding refs. Registration is lazy and HMR-safe.
   ------------------------------------------------------------------ */

type FoundryHandle = {
  /** Force-bind a single host element now (skips next scan tick). */
  bind(el: HTMLElement): void
  /** Release a host and restore its neutral state. */
  release(el: HTMLElement): void
  /** Re-scan the whole document for new hosts. */
  rescan(): void
  /** Count of live sessions this module manages. */
  count(): number
}

declare global {
  interface Window {
    __uiFoundry?: Record<string, FoundryHandle>
  }
}

function registerparallax_pointer(handle: FoundryHandle): void {
  if (!IS_BROWSER) return
  window.__uiFoundry = window.__uiFoundry ?? {}
  window.__uiFoundry['parallax-pointer'] = handle
}

const bound = new Map<HTMLElement, () => void>()

registerparallax_pointer({
  bind(el) {
    if (bound.has(el)) return
    const off = mountParallaxPointer()
    if (typeof off === 'function') bound.set(el, off)
  },
  release(el) {
    const off = bound.get(el)
    if (off) { off(); bound.delete(el) }
  },
  rescan() {
    // Legacy engines self-scan through the provider; nothing to do.
  },
  count() {
    return bound.size
  },
})

/** Dev/QA snapshot: cheap structural summary, never throws in prod. */
export function inspectparallax_pointer(): {
  module: string
  engine: string
  bound: number
  reducedMotion: boolean
} {
  return {
    module: 'parallax-pointer',
    engine: 'mountParallaxPointer',
    bound: bound.size,
    reducedMotion: prefersReducedMotion(),
  }
}

